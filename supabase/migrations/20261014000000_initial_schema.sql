-- Sentrix initial schema (see docs/sentrix-architecture.md, section 7).
--
-- Design notes:
--  * Defaults (ids, timestamps, updated_at) live in the DATABASE, so Go and
--    Python can use plain SQL without setting them (architecture gotcha #6).
--  * MACs are stored as 12 uppercase hex characters, no colons (section 5.2).
--  * Go and Python connect with a privileged role and bypass RLS. The RLS
--    policies below exist so the browser (Supabase client / Realtime) can only
--    read rows belonging to the logged-in user.

-- ---------------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------------
create type user_role as enum ('ADMIN', 'USER');
create type device_status as enum ('UNCLAIMED', 'CALIBRATING', 'ACTIVE', 'OFFLINE');
create type alert_severity as enum ('INFO', 'WARNING', 'CRITICAL');

-- ---------------------------------------------------------------------------
-- Shared trigger: keep updated_at fresh on every UPDATE
-- ---------------------------------------------------------------------------
create function set_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- users: profile row for each Supabase Auth user (same id as auth.users)
-- ---------------------------------------------------------------------------
create table users (
  id         uuid primary key references auth.users (id) on delete cascade,
  email      text not null,
  name       text,
  role       user_role not null default 'USER',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Auto-create the profile row when someone signs up.
create function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into users (id, email, name)
  values (new.id, new.email, new.raw_user_meta_data ->> 'name');
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function handle_new_user();

-- ---------------------------------------------------------------------------
-- groups: a user's collection of devices (e.g. a building / floor)
-- ---------------------------------------------------------------------------
create table groups (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references users (id) on delete cascade,
  name        text not null,
  -- 6-byte mesh id as 12 hex characters, generated by Go
  mesh_id     text not null unique check (mesh_id ~ '^[0-9A-F]{12}$'),
  description text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index groups_user_id_idx on groups (user_id);

-- ---------------------------------------------------------------------------
-- devices: one row per ESP32 (seeded at manufacturing, claimed by a user)
-- ---------------------------------------------------------------------------
create table devices (
  id                     uuid primary key default gen_random_uuid(),
  mac_address            text not null unique check (mac_address ~ '^[0-9A-F]{12}$'),
  pin_code               text not null check (pin_code ~ '^[0-9]{6}$'),
  name                   text,
  group_id               uuid references groups (id) on delete set null,
  status                 device_status not null default 'UNCLAIMED',
  calibration_started_at timestamptz,
  calibration_ends_at    timestamptz,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now()
);
create index devices_group_id_idx on devices (group_id);

-- ---------------------------------------------------------------------------
-- telemetry: one RMS current reading per device per minute
-- ---------------------------------------------------------------------------
create table telemetry (
  id          bigint generated always as identity primary key,
  device_id   uuid not null references devices (id) on delete cascade,
  "timestamp" timestamptz not null,
  rms_current double precision not null
);
-- Covers both the dashboard range queries and Python's 7-day training query.
create index telemetry_device_time_idx on telemetry (device_id, "timestamp" desc);

-- ---------------------------------------------------------------------------
-- prediction_bounds: Auto-ARIMA "safe zone" per device per hour
-- ---------------------------------------------------------------------------
create table prediction_bounds (
  id          bigint generated always as identity primary key,
  device_id   uuid not null references devices (id) on delete cascade,
  "timestamp" timestamptz not null,
  upper_bound double precision not null,
  lower_bound double precision not null,
  check (lower_bound <= upper_bound),
  -- Required so Python's bulk upsert replaces rows instead of duplicating them
  -- (architecture gotcha #5). The index also serves Go's per-hour lookup.
  unique (device_id, "timestamp")
);

-- ---------------------------------------------------------------------------
-- alerts: readings that fell outside the predicted bounds
-- ---------------------------------------------------------------------------
create table alerts (
  id            uuid primary key default gen_random_uuid(),
  device_id     uuid not null references devices (id) on delete cascade,
  "timestamp"   timestamptz not null,
  actual_value  double precision not null,
  expected_max  double precision not null,
  expected_min  double precision not null,
  severity      alert_severity not null default 'WARNING',
  is_resolved   boolean not null default false,
  -- null = unreviewed, true = real anomaly, false = false alarm
  user_feedback boolean,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index alerts_device_time_idx on alerts (device_id, "timestamp" desc);
create index alerts_unresolved_idx on alerts (device_id) where not is_resolved;

-- ---------------------------------------------------------------------------
-- push_subscriptions: Web Push endpoints (one user can have several browsers)
-- ---------------------------------------------------------------------------
create table push_subscriptions (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references users (id) on delete cascade,
  endpoint   text not null unique,
  p256dh     text not null,
  auth       text not null,
  created_at timestamptz not null default now()
);
create index push_subscriptions_user_id_idx on push_subscriptions (user_id);

-- ---------------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------------
create trigger users_updated_at   before update on users   for each row execute function set_updated_at();
create trigger groups_updated_at  before update on groups  for each row execute function set_updated_at();
create trigger devices_updated_at before update on devices for each row execute function set_updated_at();
create trigger alerts_updated_at  before update on alerts  for each row execute function set_updated_at();

-- ---------------------------------------------------------------------------
-- Row Level Security
-- The browser only ever READS (charts, Realtime). All writes go through the
-- Go API, which uses a privileged connection, so no write policies are needed
-- except where noted. With RLS on and no policy, a role is denied by default.
-- ---------------------------------------------------------------------------
alter table users              enable row level security;
alter table groups             enable row level security;
alter table devices            enable row level security;
alter table telemetry          enable row level security;
alter table prediction_bounds  enable row level security;
alter table alerts             enable row level security;
alter table push_subscriptions enable row level security;

create policy users_select_own on users
  for select to authenticated using (id = (select auth.uid()));

create policy groups_select_own on groups
  for select to authenticated using (user_id = (select auth.uid()));

-- Devices, and everything hanging off them, are visible via group ownership.
create policy devices_select_own on devices
  for select to authenticated using (
    group_id in (select id from groups where user_id = (select auth.uid()))
  );

create policy telemetry_select_own on telemetry
  for select to authenticated using (
    device_id in (
      select d.id from devices d join groups g on g.id = d.group_id
      where g.user_id = (select auth.uid())
    )
  );

create policy prediction_bounds_select_own on prediction_bounds
  for select to authenticated using (
    device_id in (
      select d.id from devices d join groups g on g.id = d.group_id
      where g.user_id = (select auth.uid())
    )
  );

create policy alerts_select_own on alerts
  for select to authenticated using (
    device_id in (
      select d.id from devices d join groups g on g.id = d.group_id
      where g.user_id = (select auth.uid())
    )
  );

create policy push_subscriptions_select_own on push_subscriptions
  for select to authenticated using (user_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- Realtime: stream new telemetry and alerts rows to the dashboard.
-- Guarded so the file also runs on plain Postgres (no supabase_realtime).
-- ---------------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table telemetry, alerts;
  end if;
end;
$$;
